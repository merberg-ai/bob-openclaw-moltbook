#!/usr/bin/env python3
"""Integrated, disposable v0.7.1 transaction and real-loopback HTTP rehearsal.

No production path, systemd, external endpoint, credential or real database.
Interruption is injected, never generated with signals. Recovery is fail-closed:
an interrupted journal is reported for manual review, NOT automatically resumed.
"""
from __future__ import annotations
import argparse
from contextlib import closing
from pathlib import Path
import sqlite3
import tempfile

import build_v071_manager_candidate as builder
from rehearse_v071_ui_update import make_stage, switch, active, validate_release, inspect_package
import rehearse_v071_transaction_safety as transaction
from rehearse_v071_http_adapter import IsolatedService, bounded_health

SCENARIOS = ("healthy", "failed-health", "failed-recovery",
             "interrupt-after-switch", "interrupt-before-switch")
EXPECTED = {
    "healthy": ("candidate_healthy", "candidate", "complete", 1),
    "failed-health": ("rolled_back", "baseline", "complete", 2),
    "failed-recovery": ("recovery_failed", "baseline", "incident", 2),
    "interrupt-after-switch": ("interrupted", "candidate", "candidate_selected", 0),
    "interrupt-before-switch": ("interrupted", "baseline", "prepared", 0),
}


def prepared_layout(root: Path):
    manager, navigation = builder.build()
    manager, navigation = inspect_package(builder.review_zip(manager, navigation))
    make_stage(root, builder.SOURCE.read_bytes(), manager, navigation)
    switch(root, "baseline")
    validate_release(root, "baseline")


def events(root: Path):
    # Use only the synthetic DB generated by make_stage.
    path = root / "state/synthetic.sqlite3"
    with closing(sqlite3.connect(path)) as conn:
        before = conn.execute("SELECT phase FROM events ORDER BY id").fetchall()
        if before != [("before",)]:
            raise AssertionError("unexpected synthetic database")
        conn.execute("INSERT INTO events(phase) VALUES ('during')")
        conn.commit()


def validate_state(root: Path, journal_root: Path, scenario: str,
                   service_starts: int):
    expected_outcome, selected, phase, starts = EXPECTED[scenario]
    if active(root) != selected:
        raise AssertionError("unexpected active release")
    validate_release(root, "baseline")
    validate_release(root, "candidate")
    record = transaction.read_journal(journal_root)
    if record is None or record["phase"] != phase or record["scenario"] != (
            scenario if scenario in transaction.SCENARIOS else "healthy"):
        raise AssertionError("transaction state drift")
    if service_starts != starts:
        raise AssertionError("service start budget mismatch")
    with closing(sqlite3.connect(root / "state/synthetic.sqlite3")) as conn:
        actual = conn.execute("SELECT phase FROM events ORDER BY id").fetchall()
        integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
    if actual != [("before",), ("during",)] or integrity != "ok":
        raise AssertionError("synthetic database write lost")
    return expected_outcome


def exercise(scenario: str) -> dict:
    if scenario not in SCENARIOS:
        raise ValueError("unsupported scenario")
    journal_scenario = scenario if scenario in transaction.SCENARIOS else "healthy"
    with tempfile.TemporaryDirectory(prefix="bob-v071-ui-") as stage_dir, \
         tempfile.TemporaryDirectory(prefix="bob-v071-journal-") as journal_dir:
        stage, journal_root = Path(stage_dir), Path(journal_dir)
        prepared_layout(stage)
        service = IsolatedService(healthy=scenario == "healthy")
        with transaction.exclusive(journal_root):
            if transaction.read_journal(journal_root) is not None:
                raise ValueError("existing journal")
            transaction.journal(journal_root, "prepared", journal_scenario)
            if scenario != "interrupt-before-switch":
                switch(stage, "candidate")
                transaction.journal(journal_root, "candidate_selected", journal_scenario)
            events(stage)
            if scenario.startswith("interrupt-"):
                # Explicitly reject a second operation after interruption.
                try:
                    if transaction.read_journal(journal_root) is None:
                        raise AssertionError("missing interrupted journal")
                    raise ValueError("incomplete transaction, operator review required")
                except ValueError as exc:
                    if str(exc) != "incomplete transaction, operator review required":
                        raise
                outcome = "interrupted"
            else:
                try:
                    service.start()
                    transaction.journal(journal_root, "restart_requested", journal_scenario)
                    if bounded_health(service):
                        transaction.journal(journal_root, "complete", journal_scenario)
                        outcome = "candidate_healthy"
                    else:
                        transaction.journal(journal_root, "health_failed", journal_scenario)
                        service.stop()
                        switch(stage, "baseline")
                        transaction.journal(journal_root, "rollback_selected", journal_scenario)
                        service.healthy = scenario == "failed-health"
                        service.start()
                        transaction.journal(journal_root, "recovery_requested", journal_scenario)
                        if bounded_health(service):
                            transaction.journal(journal_root, "complete", journal_scenario)
                            outcome = "rolled_back"
                        else:
                            transaction.journal(journal_root, "incident", journal_scenario)
                            outcome = "recovery_failed"
                finally:
                    service.stop()
            accepted_outcome = validate_state(stage, journal_root, scenario, service.starts)
            if accepted_outcome != outcome:
                raise AssertionError("unexpected lifecycle outcome")
            return {"scenario": scenario, "outcome": outcome,
                    "active_release": active(stage), "http_starts": service.starts,
                    "journal_phase": transaction.read_journal(journal_root)["phase"],
                    "synthetic_db_preserved": True,
                    "production_modified": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", choices=SCENARIOS, default="failed-health")
    args = parser.parse_args()
    try:
        result = exercise(args.scenario)
    except (OSError, RuntimeError, ValueError, AssertionError, sqlite3.Error) as exc:
        print("v0.7.1 INTEGRATED RECOVERY: REFUSED", type(exc).__name__)
        return 1
    print("v0.7.1 INTEGRATED RECOVERY: PASS")
    for name, value in result.items():
        print(name + ":", value)
    print("Synthetic directories only; no live systemd, credentials, or publishing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
